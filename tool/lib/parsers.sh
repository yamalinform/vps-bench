# parsers.sh — разбор вывода измерительных инструментов.
# shellcheck shell=bash
#
# ПРАВИЛО ЭТОГО ФАЙЛА: значение берётся по ЯКОРЮ — по имени секции, по метке,
# по структурному разделителю, — и НИКОГДА по «последнему совпадению» или по
# номеру поля без проверки. За одну сессию это правило нарушалось четырежды,
# и каждый раз давало не пропуск, а НЕВЕРНОЕ ЧИСЛО:
#
#   irtt   — брал последний "mean" из пяти секций: 14 мкс вместо 18 мс;
#   iperf3 — брал последний "bits_per_second": всегда sum_received, даже когда
#            меряется отдача (sum_sent), и при -R смысл переворачивался;
#   mbw    — брал первую строку (метод MEMCPY), хотя подпись обещала MCBLOCK:
#            10 500 вместо 17 116 МиБ/с;
#   fio    — ловил "rw":"write" из опций задачи раньше секции результатов.
#
# Каждый парсер читает ПОТОК СО ВХОДА и печатает РОВНО ОДНО число. Благодаря
# этому все они проверяются против сохранённых фикстур (`--selftest`), а не
# только на живой машине.

# --- openssl ------------------------------------------------------------------
# Формат `-mr` машиночитаемый и позиционный ПО КОНТРАКТУ:
#   +F:<idx>:<алгоритм>:<16Б>:<64Б>:<256Б>:<1КБ>:<8КБ>:<16КБ>
# Поэтому позиция допустима, но обязательна проверка: имя алгоритма совпало
# и полей ровно девять. Иначе версия openssl молча сместит колонки.
p_ossl_evp() { # <ожидаемый алгоритм> <номер поля 4|7|9>
    awk -F: -v ALG="$1" -v F="$2" '
        /^\+F/ {
            if (NF != 9) next
            name = toupper($3); want = toupper(ALG)
            gsub(/[^A-Z0-9]/, "", name); gsub(/[^A-Z0-9]/, "", want)
            if (name != want) next
            print $F; exit
        }'
}

# ` 253 bits ecdh (X25519)   0.0000s  25801.0`  -> операций в секунду
p_ossl_x25519() {
    awk '/ecdh/ && /\(X25519\)/ { print $NF; exit }'
}

# `ML-KEM-768 <t_keygen>s <t_encaps>s <t_decaps>s <keygen/s> <encaps/s> <decaps/s>`
# Полей ровно 7 — проверяем, иначе позиция бессмысленна.
p_ossl_kem() { # <keygen|encaps|decaps>
    awk -v W="$1" '
        /ML-KEM-768/ {
            if (NF != 7) next
            if (W == "keygen") print $5
            else if (W == "encaps") print $6
            else print $7
            exit
        }'
}

# --- sysbench -----------------------------------------------------------------
p_sysbench_cpu() { awk '/events per second:/ { print $NF; exit }'; }
# `2048.00 MiB transferred (42036.70 MiB/sec)` — значение в скобках, якорь по «MiB/sec»
p_sysbench_mem() { sed -n 's/.*(\([0-9.][0-9.]*\)[[:space:]]*MiB\/sec).*/\1/p' | head -1; }

# --- 7-Zip --------------------------------------------------------------------
# `Avr:  <speed> <usage> <r/u> <РЕЙТИНГ> | <speed> <usage> <r/u> <РЕЙТИНГ>`
# Якорь — структурный разделитель `|`: слева сжатие, справа распаковка,
# рейтинг в каждой половине последний. Номера полей не используются.
p_7z() { # <compress|decompress>
    awk -v W="$1" '
        /^Avr:/ {
            n = split($0, half, "|")
            if (n != 2) next
            side = (W == "compress") ? half[1] : half[2]
            k = split(side, f, /[ \t]+/)
            while (k > 0 && f[k] == "") k--
            print f[k]; exit
        }'
}

# --- mbw ----------------------------------------------------------------------
# Три метода подряд (MEMCPY, DUMB, MCBLOCK), у каждого прогоны и строка AVG.
# Якорь — имя метода И отсутствие AVG: нужен один прогон, а не среднее,
# потому что статистику по повторам считает measure().
p_mbw() { # <метод, например MCBLOCK>
    awk -v M="$1" '
        $0 ~ ("Method:[ \t]+" M) && $0 !~ /^AVG/ {
            for (i = 1; i <= NF; i++) if ($i == "Copy:") { print $(i+1); exit }
        }'
}

# --- ioping -------------------------------------------------------------------
# `min/avg/max/mdev = 426.0 us / 461.9 us / 512.2 us / 36.1 us`
# Якорь двойной: имена берутся из САМОЙ строки (слева от «=»), значение —
# из позиции с тем же номером справа. Порядок в выводе меняться может,
# и парсер это переживёт. Единица читается рядом со значением.
p_ioping_lat() { # <min|avg|max|mdev> -> микросекунды
    awk -v W="$1" '
        /min\/avg\/max/ {
            split($0, part, "=")
            nk = split(part[1], keys, "/")
            nv = split(part[2], vals, "/")
            idx = 0
            for (i = 1; i <= nk; i++) { gsub(/[^a-z]/, "", keys[i]); if (keys[i] == W) idx = i }
            if (idx == 0 || idx > nv) next
            split(vals[idx], w, /[ \t]+/)
            v = ""; u = ""
            for (j = 1; j <= 4; j++) if (w[j] != "") { if (v == "") v = w[j]; else if (u == "") u = w[j] }
            if (u == "ns") v = v / 1000
            else if (u == "ms") v = v * 1000
            else if (u == "s") v = v * 1000000
            printf "%.3f", v; exit
        }'
}

# `10.3 k requests completed in 1.99 s, 40.4 MiB read, 5.19 k iops, 20.3 MiB/s`
# Якорь — токен «iops», кратность читается из предыдущего поля.
p_ioping_seek() {
    awk '/requests completed/ {
            for (i = 1; i <= NF; i++) if ($i ~ /^iops/) {
                mult = 1; v = $(i-1)
                if (v == "k") { mult = 1000; v = $(i-2) }
                else if (v == "M") { mult = 1000000; v = $(i-2) }
                printf "%.0f", v * mult; exit
            }
        }'
}

# --- fio ----------------------------------------------------------------------
# Якорь на ЗАГОЛОВОК секции: `"read" : {` / `"write" : {`. Строка опций задачи
# `"rw" : "write"` идёт раньше и на такой якорь не попадает.
p_fio() { # <read|write> <ключ>
    awk -v S="$1" -v K="$2" '
        $0 ~ "\"" S "\" *: *\\{" { inside = 1 }
        inside && $0 ~ "\"" K "\"" { gsub(/[,"]/, "", $3); print $3; exit }'
}

# Перцентиль задержки: тройной якорь — секция чтения, блок clat_ns, блок percentile.
p_fio_pct() { # <read|write> <перцентиль, например 99.000000>
    awk -v S="$1" -v P="$2" '
        $0 ~ "\"" S "\" *: *\\{" { sec = 1 }
        sec && /"clat_ns" *: *\{/ { clat = 1 }
        clat && /"percentile" *: *\{/ { pct = 1 }
        pct && $0 ~ "\"" P "\"" { gsub(/[,"]/, "", $3); print $3; exit }'
}

# --- iperf3 -------------------------------------------------------------------
# Якорь на итоговую секцию. `bits_per_second` встречается ~10 раз: в каждом
# интервале, в каждом потоке и дважды в итогах. Для отдачи нужен sum_sent,
# для приёма sum_received — «последнее совпадение» давало всегда второе.
# ⚠ При отказе iperf3 печатает JSON с полем "error" и НУЛЯМИ в итогах. Ноль —
# валидное число, и без этой проверки он попадал в статистику как измерение:
# `tcp_up_8` вышел «0 Мбит/с» при медиане из пяти прогонов, три из которых упали.
p_iperf3() { # <sum_sent|sum_received|sum> <ключ>
    awk -v S="$1" -v K="$2" '
        /"error" *:/ { failed = 1 }
        $0 ~ "\"" S "\" *:" { inside = 1 }
        # ПЕРВОЕ совпадение после якоря и больше не берём: без флага got разбор
        # уходит в следующую секцию и снова возвращает sum_received вместо
        # sum_sent — регрессия, пойманная самопроверкой 29.08.2026.
        inside && !got && $0 ~ "\"" K "\"" { gsub(/[,"]/, "", $2); v = $2; got = 1 }
        END { if (!failed && got) print v }'
}

# --- irtt ---------------------------------------------------------------------
# Якорь на секцию "rtt": поля min/mean/max есть ещё у джиттера, send_delay,
# receive_delay и ipdv_*. Значения в наносекундах -> микросекунды.
p_irtt_rtt() { # <min|mean|max>
    awk -v K="$1" '
        /"rtt" *: *\{/ { inside = 1 }
        inside && $0 ~ "\"" K "\" *:" { gsub(/[,"]/, "", $2); printf "%.0f", $2 / 1000; exit }'
}

p_irtt_loss() {
    awk '/"packet_loss_percent"/ { gsub(/[,"]/, "", $2); print $2; exit }'
}
